/**
 * Builds the SQL that adds (or removes) the demo profiles in any database
 * (docs/plans/demo-profiles.md). Pure: no network, no AI. The SQL is
 * idempotent, so it can be re-run, for example after creating the pilot
 * event, to tag demo people with it.
 */

export const DEMO_DOMAIN = "hackamatch.invalid";

export interface DemoSeedPerson {
  name: string;
  role: "idea" | "builder" | "both";
  summary: string;
  skills: string[];
  stack: string[];
  domains: string[];
  experience: string;
  ideas?: {
    pitch: string;
    rawText: string;
    domain: string;
    skillsNeeded: string[];
    scope: string;
  }[];
}

const pad = (n: number, width: number) => String(n).padStart(width, "0");
export const demoEmail = (index: number) => `demo-${pad(index, 3)}@${DEMO_DOMAIN}`;
export const demoUserId = (index: number) => `00000000-0000-4000-d000-${pad(index, 12)}`;
export const demoIdeaId = (index: number, n: number) =>
  `00000000-0000-4000-d100-${pad(index * 10 + n, 12)}`;

const text = (value: string) => `'${value.replaceAll("'", "''")}'`;
const textArray = (values: readonly string[]) =>
  values.length ? `array[${values.map(text).join(", ")}]::text[]` : `'{}'::text[]`;

/** Which upcoming events (by date order: 1 = soonest) a demo person is going to. */
function eventRanks(index: number): number[] {
  return [[1], [1, 2], [2]][index % 3]!;
}

export function demoSeedSql(people: readonly DemoSeedPerson[]): string {
  const lines = [
    "-- Demo profiles (docs/plans/demo-profiles.md). Generated by `pnpm demo:sql`; do not edit.",
    "-- No email: the address (@" + DEMO_DOMAIN + ") is only in public.users, auth.users has",
    "-- no email, accounts are banned, notify_channel is 'none'. Remove with remove.sql.",
    // One statement (a do block), so it runs atomically through `supabase db query -f`,
    // which can't take several commands.
    "do $demo$",
    "begin",
    // Lets enforce_email_domain accept the demo domain, for this transaction only.
    "perform set_config('hackamatch.demo_seed', 'on', true);",
  ];
  people.forEach((person, i) => {
    const index = i + 1;
    const id = demoUserId(index);
    lines.push(
      "",
      `-- ${person.name}`,
      // No email in auth.users: Supabase Auth can't send a link to an account
      // without one. Every column Auth reads is filled so its user list works.
      `insert into auth.users (instance_id, id, aud, role, email, raw_user_meta_data, raw_app_meta_data,`,
      `  email_confirmed_at, banned_until, created_at, updated_at, confirmation_token, recovery_token,`,
      `  email_change_token_new, email_change, email_change_token_current, phone_change, phone_change_token,`,
      `  reauthentication_token)`,
      `values ('00000000-0000-0000-0000-000000000000', '${id}', 'authenticated', 'authenticated', null,`,
      `  jsonb_build_object('name', ${text(person.name)}, 'demo_email', ${text(demoEmail(index))}), '{}'::jsonb,`,
      `  now(), '9999-01-01', now(), now(), '', '', '', '', '', '', '', '')`,
      `on conflict (id) do nothing;`,
      `update public.users set is_demo = true, notify_channel = 'none', role = '${person.role}',`,
      `  raw_bio = ${text(person.summary)},`,
      `  onboarded_at = coalesce(onboarded_at, now())`,
      `where id = '${id}';`,
      `update public.profiles set summary = ${text(person.summary)}, skills = ${textArray(person.skills)},`,
      `  stack = ${textArray(person.stack)}, domains = ${textArray(person.domains)},`,
      `  experience_level = '${person.experience}'`,
      `where user_id = '${id}';`,
    );
    (person.ideas ?? []).forEach((idea, n) => {
      lines.push(
        `insert into public.ideas (id, owner_id, raw_text, pitch, domain, skills_needed, scope)`,
        `values ('${demoIdeaId(index, n)}', '${id}', ${text(idea.rawText)}, ${text(idea.pitch)}, ${text(idea.domain)}, ${textArray(idea.skillsNeeded)}, '${idea.scope}')`,
        `on conflict (id) do nothing;`,
      );
    });
    lines.push(
      `insert into public.event_interests (user_id, event_id)`,
      `select '${id}', e.id from (select id, row_number() over (order by start_date, id) as rank`,
      `  from public.events where end_date >= current_date) e`,
      `where e.rank = any (array[${eventRanks(i).join(", ")}])`,
      `on conflict do nothing;`,
    );
  });
  lines.push("", "end", "$demo$;", "");
  return lines.join("\n");
}

export const DEMO_REMOVE_SQL = [
  "-- Removes every demo profile and everything it owns (ideas, interests, matches, teams).",
  `delete from auth.users where id in (select id from public.users where is_demo);`,
  "",
].join("\n");
